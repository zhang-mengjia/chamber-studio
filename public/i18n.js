// Capture only the original static HTML; user text and SVG artwork are untouched.
export function staticTranslator(root){
  const nodes=[],attrs=[];
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){const node=walker.currentNode;if(english[node.textContent.trim()])nodes.push([node,node.textContent.trim()]);}
  for(const node of root.querySelectorAll('[title],[aria-label],meta[name="description"]'))for(const attr of ['title','aria-label','content']){
    const value=node.getAttribute(attr);if(value&&english[value])attrs.push([node,attr,value]);
  }
  return ()=>{document.documentElement.lang=language==='zh'?'zh-CN':'en';for(const [node,value]of nodes)node.textContent=t(value);for(const [node,attr,value]of attrs)node.setAttribute(attr,t(value));};
}
